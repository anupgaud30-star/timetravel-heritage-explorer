export function findMatchingMonument(query: string, additionalContext?: string): Monument | undefined {
  if (!query && !additionalContext) return undefined;
  const q = (query || "").toLowerCase();
  const ctx = (additionalContext || "").toLowerCase();
  const combined = `${q} ${ctx}`;

  // 1. Check exact ID or specific curated aliases
  for (const monument of monuments) {
    const aliases = monumentAliases[monument.id] || monument.aliases || [];
    if (aliases.some((alias) => q.includes(alias.toLowerCase()))) {
      return monument;
    }
  }

  // 2. Direct name match in query
  for (const monument of monuments) {
    const nameLower = monument.name.toLowerCase();
    if (q.includes(nameLower)) return monument;
  }

  // 3. Simplified name token match (e.g. "daulatabad" in "Why was Daulatabad Fort important?")
  for (const monument of monuments) {
    const simplified = monument.name
      .toLowerCase()
      .replace(/(temple|fort|caves|monument|stupa|palace|memorial|complex|sun|station|\(.*\))/g, "")
      .trim();
    if (simplified.length >= 4 && q.includes(simplified)) {
      return monument;
    }
  }

  // 4. Check answer/context text for aliases
  for (const monument of monuments) {
    const aliases = monumentAliases[monument.id] || monument.aliases || [];
    if (aliases.some((alias) => ctx.includes(alias.toLowerCase()))) {
      return monument;
    }
  }

  // 5. Check answer/context text for direct name
  for (const monument of monuments) {
    const nameLower = monument.name.toLowerCase();
    if (ctx.includes(nameLower)) return monument;
  }

  return undefined;
}
